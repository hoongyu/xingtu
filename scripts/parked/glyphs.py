"""星官图形族。

一个族一套骨架，变体只改局部 —— 人物只有一副身架，帝/官/女/武的差别
在冠和手持物；四足只有一副骨架，犬/马/兽差在比例。这样 308 个星官的
风格一致是结构保证的，不靠一张张对着调。

坐标系：以星官质心为原点，x 沿主轴，单位 = 主轴半跨度。
图形画在 x∈[-1,1]、y∈[-1,1] 附近。y 向下为正（跟 SVG 一致）。
"""
import math

from ribbon import ribbon
from plume import circle


def _pts(*xy):
    return 'M' + ' L'.join(f"{x:.3f} {y:.3f}" for x, y in xy) + ' Z'


# ────────────────────────── 人物 ──────────────────────────
# 深衣的轮廓：肩窄、袖宽、下摆最阔。这个剪影在很小的尺寸上也认得出是人。

_ROBE = ("M-0.11 -0.52 "
         "C-0.30 -0.47 -0.40 -0.28 -0.43 -0.06 "
         "C-0.34 -0.02 -0.28 -0.06 -0.25 -0.14 "
         "C-0.28 0.14 -0.33 0.40 -0.37 0.62 "
         "L0.37 0.62 "
         "C0.33 0.40 0.28 0.14 0.25 -0.14 "
         "C0.28 -0.06 0.34 -0.02 0.43 -0.06 "
         "C0.40 -0.28 0.30 -0.47 0.11 -0.52 Z")

_SASH = ("M-0.26 -0.02 C-0.10 0.04 0.10 0.04 0.26 -0.02 "
         "M-0.02 0.06 L-0.05 0.44 M0.02 0.06 L0.05 0.44")


def _head(cy=-0.70, r=0.145):
    return circle(0, cy, r)


def figure(kind='official'):
    """人物。kind: emperor / official / lady / warrior。"""
    body = _ROBE
    detail = _SASH
    head = _head()
    extra = ''

    if kind == 'emperor':
        # 冕：平顶延板 + 前后垂旒。皇帝就靠这块板认出来。
        extra = (_pts((-0.30, -0.90), (0.30, -0.90), (0.30, -0.83), (-0.30, -0.83))
                 + ' ' + _pts((-0.14, -0.83), (0.14, -0.83), (0.12, -0.76), (-0.12, -0.76)))
        detail += (" M-0.22 -0.83 L-0.22 -0.62 M-0.11 -0.83 L-0.11 -0.60"
                   " M0.11 -0.83 L0.11 -0.60 M0.22 -0.83 L0.22 -0.62")
    elif kind == 'official':
        # 进贤冠：前低后高的梯形
        extra = _pts((-0.17, -0.82), (0.17, -0.86), (0.15, -0.79), (-0.15, -0.78))
    elif kind == 'lady':
        # 双鬟：两个发髻。身形也收窄一点。
        head = _head(-0.68, 0.135)
        extra = circle(-0.17, -0.84, 0.085) + ' ' + circle(0.17, -0.84, 0.085)
        body = _ROBE.replace('0.37 0.62', '0.31 0.64').replace('-0.37 0.62', '-0.31 0.64')
    elif kind == 'warrior':
        # 兜鍪加缨，右手持戟
        extra = (_pts((-0.17, -0.80), (0.17, -0.80), (0.13, -0.90), (-0.13, -0.90))
                 + ' ' + _pts((-0.03, -0.90), (0.03, -0.90), (0.05, -1.02), (-0.05, -1.00)))
        detail += " M0.52 -0.86 L0.52 0.56 M0.52 -0.86 L0.44 -0.70 M0.52 -0.86 L0.60 -0.70"

    return {'d': head + ' ' + body + ' ' + extra, 'vein': detail}


# ────────────────────────── 走兽 ──────────────────────────

def quadruped(kind='beast'):
    """四足。kind: beast / dog / horse / turtle。"""
    if kind == 'turtle':
        body = circle(0, 0, 0.46).replace('a0.4600', 'a0.4600')
        shell = (" M-0.30 -0.16 L0.30 -0.16 M-0.34 0.02 L0.34 0.02 M-0.30 0.20 L0.30 0.20"
                 " M-0.10 -0.34 L-0.10 0.34 M0.10 -0.34 L0.10 0.34")
        head = _pts((0.44, -0.06), (0.66, -0.10), (0.70, 0.00), (0.62, 0.08), (0.44, 0.06))
        legs = ' '.join(_pts(*p) for p in (
            ((-0.34, -0.36), (-0.46, -0.52), (-0.30, -0.46), (-0.24, -0.32)),
            ((0.34, -0.36), (0.48, -0.52), (0.32, -0.46), (0.26, -0.32)),
            ((-0.34, 0.36), (-0.46, 0.52), (-0.30, 0.46), (-0.24, 0.32)),
            ((0.34, 0.36), (0.48, 0.52), (0.32, 0.46), (0.26, 0.32))))
        tail = _pts((-0.44, 0.00), (-0.66, -0.04), (-0.64, 0.06))
        return {'d': body + ' ' + head + ' ' + legs + ' ' + tail,
                'vein': shell, 'eye': circle(0.60, -0.02, 0.030)}

    # 躯干要够厚、头要前伸而不是上仰 —— 头一上仰就像猫在张望，不像走兽。
    deep = {'dog': .21, 'horse': .23, 'beast': .24}.get(kind, .23)
    trunk = ribbon([(-0.64, -0.02), (-0.32, -0.12), (0.08, -0.14), (0.46, -0.08)],
                   [.05, deep, deep, deep * .82], n=6, tip=False)
    neck = ribbon([(0.42, -0.12), (0.62, -0.24), (0.76, -0.34)],
                  [deep * .78, .13, .10], n=4, tip=False)
    head = _pts((0.70, -0.42), (0.96, -0.44), (1.04, -0.34), (0.94, -0.26), (0.72, -0.26))
    ear = (_pts((0.76, -0.42), (0.74, -0.60), (0.86, -0.46)) if kind != 'horse'
           else _pts((0.78, -0.44), (0.80, -0.62), (0.88, -0.46)))
    legs = ' '.join(ribbon(pp, [.075, .055, .042], n=4, tip=False) for pp in (
        [(-0.46, 0.06), (-0.52, 0.32), (-0.44, 0.62)],
        [(-0.28, 0.08), (-0.22, 0.34), (-0.28, 0.62)],
        [(0.22, 0.06), (0.30, 0.32), (0.24, 0.62)],
        [(0.40, 0.06), (0.46, 0.32), (0.40, 0.62)]))
    hoof = ' '.join(_pts((x - 0.07, 0.60), (x + 0.07, 0.60), (x + 0.06, 0.68), (x - 0.06, 0.68))
                    for x in (-0.44, -0.28, 0.24, 0.40))
    tail = (ribbon([(-0.62, -0.08), (-0.82, -0.22), (-0.96, -0.44)], [.055, .04, .0], n=4)
            if kind != 'horse'
            else ribbon([(-0.62, -0.10), (-0.84, 0.06), (-0.94, 0.40)], [.07, .09, .0], n=5))
    mane = (" M0.46 -0.24 L0.58 -0.42 M0.54 -0.22 L0.66 -0.40 M0.62 -0.24 L0.72 -0.40"
            if kind == 'horse' else '')
    return {'d': ' '.join([trunk, neck, head, ear, legs, hoof, tail]),
            'vein': mane, 'eye': circle(0.90, -0.36, 0.034)}


# ────────────────────────── 飞禽与水族 ──────────────────────────

def bird(kind='bird'):
    """禽。kind: bird（展翅）/ fish / bug。"""
    if kind == 'fish':
        body = ribbon([(-0.58, 0.00), (-0.20, -0.02), (0.24, 0.00), (0.52, 0.02)],
                      [.0, .26, .20, .06], n=6, tip=False)
        tail = _pts((0.50, 0.02), (0.88, -0.24), (0.78, 0.02), (0.90, 0.26))
        fin = _pts((-0.06, 0.18), (0.10, 0.42), (0.22, 0.16))
        dorsal = _pts((-0.10, -0.22), (0.06, -0.46), (0.24, -0.18))
        gill = " M-0.34 -0.14 C-0.28 0.00 -0.28 0.06 -0.34 0.18"
        scales = ' '.join(f"M{x:.2f} {-0.16 + .10 * r:.2f} q0.07 {0.05:.2f} 0 0.10"
                          for r in range(4) for x in (-0.24, -0.08, 0.08))
        return {'d': body + ' ' + tail + ' ' + fin + ' ' + dorsal,
                'vein': gill + ' ' + scales, 'eye': circle(-0.40, -0.05, 0.035)}

    if kind == 'bug':
        body = ribbon([(-0.36, 0.00), (0.00, 0.00), (0.34, 0.00)],
                      [.12, .22, .10], n=5, tip=False)
        wing = (ribbon([(-0.06, -0.10), (-0.26, -0.44), (-0.48, -0.56)], [.10, .12, .0], n=4)
                + ' ' + ribbon([(-0.02, 0.10), (-0.22, 0.44), (-0.44, 0.56)], [.10, .12, .0], n=4))
        head = circle(0.42, 0.00, 0.13)
        ant = " M0.50 -0.08 L0.68 -0.28 M0.52 0.06 L0.72 0.20"
        stripe = " M-0.20 -0.19 L-0.20 0.19 M-0.04 -0.22 L-0.04 0.22 M0.12 -0.20 L0.12 0.20"
        return {'d': body + ' ' + wing + ' ' + head,
                'vein': ant + stripe, 'eye': circle(0.46, -0.04, 0.035)}

    # 展翅飞鸟。翼要画成整片后掠面、后缘开羽缺 —— 先前拿三根散羽拼，
    # 出来像蜻蜓不像鸟。羽缺才是让人一眼认出「翅膀」的东西。
    body = ribbon([(-0.62, 0.10), (-0.24, 0.02), (0.22, -0.02), (0.58, -0.08)],
                  [.0, .14, .17, .10], n=6, tip=False)
    neck = ribbon([(0.52, -0.08), (0.72, -0.20), (0.86, -0.32)],
                  [.10, .075, .06], n=4, tip=False)
    head = circle(0.90, -0.36, 0.105)
    bill = _pts((0.98, -0.38), (1.22, -0.42), (0.98, -0.30))

    def _wing(s_):
        """肩 → 前缘 → 翼尖 → 后缘（三个羽缺）→ 回到体侧。"""
        sh, tip_ = (0.16, s_ * 0.02), (-0.52, s_ * 0.92)
        d = [f"M{sh[0]:.3f} {sh[1]:.3f}"]
        d.append(f"C{0.06:.3f} {s_*0.40:.3f} {-0.20:.3f} {s_*0.74:.3f} "
                 f"{tip_[0]:.3f} {tip_[1]:.3f}")
        # 后缘：自翼尖回收，凹三个缺口
        for a, b in ((-0.44, 0.74), (-0.30, 0.52), (-0.14, 0.30)):
            d.append(f"Q{a - 0.10:.3f} {s_*(b + 0.10):.3f} {a:.3f} {s_*b:.3f}")
        d.append(f"C{-0.04:.3f} {s_*0.18:.3f} {0.04:.3f} {s_*0.08:.3f} "
                 f"{sh[0]:.3f} {sh[1]:.3f} Z")
        return ' '.join(d)

    wings = _wing(-1) + ' ' + _wing(1)
    tailf = ' '.join(ribbon([(-0.56, 0.06), (-0.80, 0.06 + t), (-1.02, 0.06 + t * 2.0)],
                            [.06, .05, .0], n=4) for t in (-0.15, 0.0, 0.15))
    quills = ' '.join(f"M0.14 {s_*0.04:.2f} C-0.06 {s_*0.36:.2f} -0.28 {s_*0.66:.2f} "
                      f"-0.48 {s_*0.86:.2f}" for s_ in (-1, 1))
    return {'d': ' '.join([body, neck, head, bill, wings, tailf]),
            'vein': quills, 'eye': circle(0.92, -0.39, 0.033)}


# ────────────────────────── 车船 ──────────────────────────

def vessel(kind='boat'):
    if kind == 'boat':
        hull = ("M-0.86 -0.02 C-0.60 0.30 0.60 0.30 0.86 -0.02 "
                "C0.60 0.12 -0.60 0.12 -0.86 -0.02 Z")
        deck = "M-0.80 -0.02 L0.80 -0.02"
        mast = _pts((-0.03, -0.06), (0.03, -0.06), (0.03, -0.86), (-0.03, -0.86))
        sail = ("M0.05 -0.80 C0.42 -0.62 0.46 -0.30 0.30 -0.12 L0.05 -0.12 Z")
        rib = " M-0.50 -0.02 L-0.44 0.14 M-0.18 -0.02 L-0.16 0.20 M0.18 -0.02 L0.16 0.20 M0.50 -0.02 L0.44 0.14"
        return {'d': hull + ' ' + mast + ' ' + sail, 'vein': deck + rib, 'eye': ''}

    # 车：厢 + 两轮 + 辕
    box = _pts((-0.46, -0.10), (0.30, -0.10), (0.30, 0.22), (-0.46, 0.22))
    canopy = _pts((-0.54, -0.14), (0.38, -0.14), (0.30, -0.34), (-0.46, -0.34))
    pole = ribbon([(0.30, 0.10), (0.66, 0.02), (0.94, -0.06)], [.035, .03, .022], n=4, tip=False)
    wheels = circle(-0.30, 0.34, 0.26) + ' ' + circle(0.16, 0.34, 0.26)
    spokes = ' '.join(f"M{cx:.2f} {0.34:.2f} L{cx + 0.26 * math.cos(a):.3f} {0.34 + 0.26 * math.sin(a):.3f}"
                      for cx in (-0.30, 0.16) for a in [k * math.pi / 3 for k in range(6)])
    return {'d': box + ' ' + canopy + ' ' + pole + ' ' + wheels, 'vein': spokes, 'eye': ''}


# ────────────────────────── 建筑 ──────────────────────────

def structure(kind='hall'):
    if kind == 'gate':
        # 阙：两座高台夹一道门。先前把屋盖画成半圆，出来像两朵蘑菇；
        # 中国的阙是层层收分的方檐，得用直棱。
        def tower(x):
            body_ = _pts((x - 0.15, 0.64), (x + 0.15, 0.64), (x + 0.11, -0.30), (x - 0.11, -0.30))
            eaves = ' '.join(
                _pts((x - w, y), (x + w, y), (x + w - 0.05, y - 0.11), (x - w + 0.05, y - 0.11))
                for w, y in ((0.30, -0.30), (0.24, -0.47), (0.17, -0.62)))
            finial = _pts((x - 0.04, -0.73), (x + 0.04, -0.73), (x + 0.02, -0.86), (x - 0.02, -0.86))
            return body_ + ' ' + eaves + ' ' + finial
        lintel = _pts((-0.42, -0.06), (0.42, -0.06), (0.42, 0.06), (-0.42, 0.06))
        return {'d': tower(-0.58) + ' ' + tower(0.58) + ' ' + lintel,
                'vein': " M-0.47 0.26 L-0.47 0.62 M0.47 0.26 L0.47 0.62"
                        " M-0.42 0.00 L0.42 0.00", 'eye': ''}
    if kind == 'wall':
        # 垣墙：带垛口的一段城墙
        top = -0.22
        merl = ' '.join(_pts((x, top), (x + 0.14, top), (x + 0.14, top - 0.16), (x, top - 0.16))
                        for x in [-0.90 + 0.30 * k for k in range(7)])
        body = _pts((-0.96, top), (0.96, top), (0.96, 0.56), (-0.96, 0.56))
        brick = ' '.join(f"M-0.96 {y:.2f} L0.96 {y:.2f}" for y in (0.00, 0.22, 0.44))
        return {'d': body + ' ' + merl, 'vein': brick, 'eye': ''}
    if kind == 'granary':
        # 囷仓：圆廪加锥顶
        body = _pts((-0.52, -0.10), (0.52, -0.10), (0.44, 0.60), (-0.44, 0.60))
        roof = _pts((-0.62, -0.10), (0.62, -0.10), (0.00, -0.66))
        door = _pts((-0.12, 0.24), (0.12, 0.24), (0.12, 0.60), (-0.12, 0.60))
        hoop = " M-0.50 0.08 L0.50 0.08 M-0.47 0.34 L0.47 0.34"
        return {'d': body + ' ' + roof, 'vein': hoop + ' ' + door.replace('M', 'M'), 'eye': ''}
    # hall：单檐歇山，台基抬起
    roof = ("M-0.92 -0.16 C-0.56 -0.56 0.56 -0.56 0.92 -0.16 "
            "C0.60 -0.30 -0.60 -0.30 -0.92 -0.16 Z")
    ridge = "M-0.62 -0.34 L0.62 -0.34"
    cols = ' '.join(_pts((x - 0.05, -0.20), (x + 0.05, -0.20), (x + 0.05, 0.42), (x - 0.05, 0.42))
                    for x in (-0.56, -0.19, 0.19, 0.56))
    base = _pts((-0.86, 0.42), (0.86, 0.42), (0.78, 0.62), (-0.78, 0.62))
    return {'d': roof + ' ' + cols + ' ' + base, 'vein': ridge, 'eye': ''}


# ────────────────────────── 器具 ──────────────────────────

def implement(kind='mark'):
    if kind == 'weapon':
        # 钺：长柄阔刃
        shaft = ribbon([(-0.10, 0.86), (0.00, 0.00), (0.06, -0.80)], [.045, .045, .04], n=4, tip=False)
        blade = ("M0.04 -0.62 C0.44 -0.76 0.62 -0.44 0.46 -0.14 "
                 "C0.34 -0.22 0.16 -0.26 0.02 -0.24 Z")
        return {'d': shaft + ' ' + blade, 'vein': " M0.10 -0.56 C0.36 -0.62 0.46 -0.42 0.40 -0.22", 'eye': ''}
    if kind == 'banner':
        pole = ribbon([(-0.52, 0.90), (-0.48, 0.00), (-0.44, -0.86)], [.04, .04, .03], n=4, tip=False)
        flag = ("M-0.42 -0.80 C0.10 -0.72 0.34 -0.52 0.86 -0.44 "
                "C0.40 -0.30 0.20 -0.10 -0.34 -0.06 Z")
        streak = (" M-0.30 -0.66 C0.12 -0.58 0.34 -0.44 0.70 -0.40"
                  " M-0.34 -0.44 C0.06 -0.38 0.26 -0.26 0.56 -0.24")
        finial = _pts((-0.44, -0.86), (-0.40, -1.02), (-0.36, -0.86))
        return {'d': pole + ' ' + flag + ' ' + finial, 'vein': streak, 'eye': ''}
    if kind == 'sky':
        # 云雷：三叠云头 + 一道电
        cloud = ("M-0.86 0.16 C-0.90 -0.14 -0.60 -0.30 -0.40 -0.18 "
                 "C-0.30 -0.48 0.12 -0.50 0.24 -0.22 "
                 "C0.54 -0.34 0.82 -0.12 0.72 0.16 Z")
        bolt = _pts((0.06, 0.14), (0.34, 0.14), (0.14, 0.46), (0.34, 0.44),
                    (-0.02, 0.92), (0.06, 0.50), (-0.14, 0.52))
        return {'d': cloud + ' ' + bolt, 'vein': '', 'eye': ''}
    if kind == 'mansion':
        # 宿：月亮的驿站。新月抱一颗星 —— 二十八宿本义就是月行所舍，
        # 这比方块记号既准确又好看。
        crescent = ("M0.10 -0.78 C-0.52 -0.62 -0.80 -0.10 -0.62 0.42 "
                    "C-0.44 0.90 0.10 1.02 0.44 0.78 "
                    "C-0.02 0.84 -0.36 0.52 -0.38 0.06 "
                    "C-0.40 -0.34 -0.20 -0.66 0.10 -0.78 Z")
        star = _pts((0.46, -0.52), (0.56, -0.24), (0.84, -0.16),
                    (0.56, -0.06), (0.46, 0.22), (0.36, -0.06),
                    (0.08, -0.16), (0.36, -0.24))
        return {'d': crescent + ' ' + star, 'vein': '', 'eye': ''}
    # mark：环珠。给那些一两颗星、传统本来就不作画的星官一个中性记号，
    # 不假装它有形象 —— 这跟当初否掉天秤座是同一条底线。
    return {'d': circle(0, 0, 0.40), 'vein': circle(0, 0, 0.62), 'eye': circle(0, 0, 0.13)}


