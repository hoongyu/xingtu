# ────────────────────── 补：二十八宿与常见名物 ──────────────────────
# 二十八宿是最要紧的一批，给方块记号太敷衍。名字本身多是具象的
# （斗、井、箕、毕、柳、角……），就照本义画。

def ladle():
    """斗：柄 + 方勺。北斗、南斗、小斗、斗宿共用。"""
    bowl = _pts((-0.66, -0.30), (0.06, -0.30), (0.02, 0.34), (-0.58, 0.34))
    handle = ribbon([(0.04, -0.14), (0.52, -0.36), (0.92, -0.64)],
                    [.075, .06, .05], n=4, tip=False)
    rim = " M-0.62 -0.16 L0.04 -0.16"
    return {'d': bowl + ' ' + handle, 'vein': rim, 'eye': ''}


def net():
    """毕：长柄小网。《诗》「有兔爰爰，雉离于罗」的那种网。"""
