def build():
    # 按「扇区 × 层级」分桶。只按扇区分的话，同层同扇区的两个概念半径一样、
    # 角度又挨着，会贴到几乎重合（自然语言处理 ↔ 语言模型曾只差 5 个单位）。
    bucket = {}
    for name, sec, lv, imp, hard, note in N:
        bucket.setdefault((sec, lv), []).append(name)

    idx = {}
    stars = {}
    names = {}
    notes = {}
    for name, sec, lv, imp, hard, note in N:
        peers = bucket[(sec, lv)]
        k = peers.index(name)
        # 同一环上把本扇区的概念铺满扇区宽度；只有一个就摆正中
        span = 24
        frac = 0.0 if len(peers) == 1 else ((k + .5) / len(peers) - .5)
        ang = math.radians(sec * 30 + frac * span - 90)
        r = LEVEL_R[lv]
        # [x, y, 重要度, 难度, 层级, 扇区] —— 前两位是位置，渲染器只认这两位
        stars[name] = [round(math.cos(ang) * r, 2), round(math.sin(ang) * r, 2),
                       imp, hard, lv, sec]
        names[name] = name
        notes[name] = note
        idx[name] = (sec, lv)

    missing = set()

    def groups(d, kind):
        out = []
        for gname, members in d.items():
            ms = [m for m in members if m in stars]
            missing.update(set(members) - set(stars))
            if len(ms) < 2:
                continue
            # 折线按给定顺序穿过成员 —— 那个顺序本身是「这条思路的线索」
            out.append({'name': gname, 'en': '', 'py': kind,
                        'lines': [ms]})
        return out

    cultures = {
        'lineage': {'label': '技术谱系', 'groups': groups(LINEAGE, 'lineage')},
        'pipeline': {'label': '训练流水线', 'groups': groups(PIPELINE, 'pipeline')},
    }
    assert not missing, f"划法里引用了不存在的概念：{sorted(missing)}"

    used = {m for c in cultures.values() for g in c['groups'] for m in g['lines'][0]}
    orphan = sorted(set(stars) - used - {'人工智能'})
    assert not orphan, f"这些概念没有被任何一种划法收进去：{orphan}"

    payload = {
        'meta': {'root': '人工智能', 'sectors': SECTORS,
                 'levels': LEVEL_R, 'outer': OUTER,
                 'note': '半径=抽象层级，角度=领域扇区。两种划法都不参与定位。'},
        'stars': stars, 'names': names, 'notes': notes, 'lore': LORE,
        'lunar_mansions': [],
        'cultures': cultures,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, separators=(',', ':')),
                   encoding='utf-8')

    print(f"概念 {len(stars)} 个   扇区 {len(SECTORS)}   层级 {len(LEVEL_R)}")
    for k, c in cultures.items():
        print(f"  {c['label']}: {len(c['groups'])} 组   "
              f"覆盖 {len({m for g in c['groups'] for m in g['lines'][0]})} 个概念")
    lv = {}
    for name, sec, l, *_ in N:
        lv[l] = lv.get(l, 0) + 1
    print('  层级分布:', '  '.join(f'{k}:{v}' for k, v in sorted(lv.items())))
    print(f"\n  -> {OUT.relative_to(OUT.parents[2])}  {OUT.stat().st_size/1024:.0f} KB")


if __name__ == '__main__':
    build()
