def check_terms():
    """界表的出厂检验。写错一个数就在这里断掉，不会流到页面上。

    两条性质：每宫五段合计三十度且首尾相接不留缝；
    五星在整条黄道上各占的总度数是固定的（土57 木79 火66 金82 水76，
    合计 360）—— 后面这条是这套埃及界表流传下来就带着的，抄错必然对不上。"""
    tot = {}
    for sign, segs in TERMS.items():
        assert segs[0][1] == 0 and segs[-1][2] == 30, f'{sign} 界首尾不对'
        assert sum(b - a for _, a, b in segs) == 30, f'{sign} 界合计不是 30 度'
        for i in range(len(segs) - 1):
            assert segs[i][2] == segs[i + 1][1], f'{sign} 界第 {i+1} 段留缝'
        for pl, a, b in segs:
            tot[pl] = tot.get(pl, 0) + (b - a)
    assert tot == TERM_TOTALS, f'界表各星总度数对不上：{tot}'
    assert sum(len(v) for v in FACES.values()) == 36, '面不是三十六个'
    return tot


def mansions():
    """二十八宿的赤经界限，取自距星实测位置（J2000）。"""
    lm = SKY['lunar_mansions']
    rows = sorted((SKY['stars'][str(h)][0], SKY['names'][str(h)]) for h in lm)
    out = []
    for i, (ra, nm) in enumerate(rows):
        nxt = rows[(i + 1) % len(rows)][0]
        span = (nxt - ra) % 360
        n = nm[:-2] if nm.endswith('宿一') else nm
        fy = FENYE[n]
        out.append({'n': n, 'ra': round(ra, 3), 'deg': round(span, 3),
                    'xiang': XIANG[n], 'guo': fy[0], 'zhou': fy[1],
                    'zhan': XIU_ZHAN[n]})
    # 出口断言：分野、四象、占辞三张表必须各覆盖二十八宿，
    # 少一条不会报错，只会让某颗星落进去时读不出东西。
    got = {x['n'] for x in out}
    for nm2, tbl in (('四象', XIANG), ('分野', FENYE), ('占辞', XIU_ZHAN)):
        miss = got - set(tbl)
        assert not miss, f"{nm2}表缺这些宿：{sorted(miss)}"
    return out


